    function calculatePlayerStats(playerName) {
      const stats = {
        rank: 0,
        matchesPlayed: 0,
        wins: 0,
        losses: 0,
        points: 0,
        winRate: 0,
        setsWon: 0,
        setsLost: 0,
        setWinRate: 0,
        matches: [],
        h2h: {},
        recentForm: [],
        monthlyStats: {}
      };

      // Get latest standings to find rank
      const latestMonth = Object.keys(tournamentData)[Object.keys(tournamentData).length - 1];
      const latestStandings = tournamentData[latestMonth].standings;
      const playerStanding = latestStandings.find(p => p.name === playerName);

      if (playerStanding) {
        stats.rank = playerStanding.position;
        stats.matchesPlayed = playerStanding.matches_played;
        stats.points = playerStanding.points;
      }

      // Go through all matches
      Object.entries(tournamentData).forEach(([monthKey, data]) => {
        const monthName = monthNames[monthKey];

        // Initialize monthly stats
        if (!stats.monthlyStats[monthName]) {
          stats.monthlyStats[monthName] = {
            wins: 0,
            losses: 0,
            points: 0
          };
        }

        data.matches.forEach(match => {
          if (match.player1 === playerName || match.player2 === playerName) {
            const isPlayer1 = match.player1 === playerName;
            const opponent = isPlayer1 ? match.player2 : match.player1;

            if (match.score && match.score !== 'αναβολή') {
              // Parse score to determine winner
              const setMatches = match.score.match(/\(\s*(\d+)-(\d+)\s*\)/g);
              if (setMatches) {
                let player1Sets = 0;
                let player2Sets = 0;

                setMatches.forEach(setScore => {
                  const scores = setScore.match(/\(\s*(\d+)-(\d+)\s*\)/);
                  if (scores) {
                    const p1Score = parseInt(scores[1]);
                    const p2Score = parseInt(scores[2]);
                    if (p1Score > p2Score) {
                      player1Sets++;
                      if (isPlayer1) stats.setsWon++;
                      else stats.setsLost++;
                    } else if (p2Score > p1Score) {
                      player2Sets++;
                      if (isPlayer1) stats.setsLost++;
                      else stats.setsWon++;
                    }
                  }
                });

                // Check tie-break
                if (player1Sets === 1 && player2Sets === 1) {
                  const tiebreakMatch = match.score.match(/(?:TB|tie|ΤΒ)\s*(\d+)-(\d+)/i);
                  if (tiebreakMatch) {
                    const tb1 = parseInt(tiebreakMatch[1]);
                    const tb2 = parseInt(tiebreakMatch[2]);
                    if (tb1 > tb2) {
                      player1Sets++;
                      if (isPlayer1) stats.setsWon++;
                      else stats.setsLost++;
                    } else {
                      player2Sets++;
                      if (isPlayer1) stats.setsLost++;
                      else stats.setsWon++;
                    }
                  }
                }

                const playerWon = isPlayer1 ? player1Sets > player2Sets : player2Sets > player1Sets;

                if (playerWon) {
                  stats.wins++;
                  stats.monthlyStats[monthName].wins++;
                  stats.monthlyStats[monthName].points += 2;
                  stats.recentForm.push('win');
                } else {
                  stats.losses++;
                  stats.monthlyStats[monthName].losses++;
                  stats.monthlyStats[monthName].points += 1;
                  stats.recentForm.push('loss');
                }

                stats.matches.push({
                  date: formatDate(match.date),
                  month: monthName,
                  opponent: opponent,
                  isHome: isPlayer1,
                  result: playerWon ? 'win' : 'loss',
                  score: match.score
                });

                // Update H2H
                if (!stats.h2h[opponent]) {
                  stats.h2h[opponent] = { wins: 0, losses: 0 };
                }
                if (playerWon) {
                  stats.h2h[opponent].wins++;
                } else {
                  stats.h2h[opponent].losses++;
                }
              }
            }
          }
        });
      });

      // Sort matches by date (most recent first)
      stats.matches.reverse();

      // Keep only last 5 for recent form
      stats.recentForm = stats.recentForm.slice(-5).reverse();

      // Calculate win rate
      if (stats.wins + stats.losses > 0) {
        stats.winRate = Math.round((stats.wins / (stats.wins + stats.losses)) * 100);
      }

      // Calculate set win rate
      if (stats.setsWon + stats.setsLost > 0) {
        stats.setWinRate = Math.round((stats.setsWon / (stats.setsWon + stats.setsLost)) * 100);
      }

      return stats;
    }

