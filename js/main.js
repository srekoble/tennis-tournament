    function detectMonthFromFilename(filename) {
      const upperName = filename.toUpperCase();

      // October - ΟΚΤΩΒΡΗΣ
      if (upperName.includes('ΟΚΤΩΒΡ') || upperName.includes('OCTOB')) {
        return 'ΟΚΤΩΒΡΗΣ';
      }

      // November - ΝΟΕΜΒΡΗΣ  
      if (upperName.includes('ΝΟΕΜΒΡ') || upperName.includes('NOVEMB')) {
        return 'ΝΟΕΜΒΡΗΣ';
      }

      // December - ΔΕΚΕΜΒΡΗΣ
      if (upperName.includes('ΔΕΚΕΜΒΡ') || upperName.includes('DECEMB')) {
        return 'ΔΕΚΕΜΒΡΗΣ';
      }

      // January - IANOΥΑΡΙΟΣ 
      // Handles: ΙΑΝΟΥΑΡΙΟΣ (all Greek), IANOΥΑΡΙΟΣ (mixed), IANOY, January, etc.
      if (upperName.includes('ΙΑΝΟΥΑΡ') ||
        upperName.includes('IANOUARI') ||
        upperName.startsWith('IANO') ||  // Catches IANOΥ... pattern
        upperName.includes('IANOY') ||
        upperName.includes('JANUAR')) {
        return 'IANOΥΑΡΙΟΣ';
      }

      return null;
    }

    function parseCSV(csvText, fileName) {
      const lines = csvText.split('\n');
      const matches = [];
      const standings = [];
      let currentDate = null;

      for (let line of lines) {
        const cols = line.split(';');

        // Check for date (but don't skip the rest - same line might have standings!)
        if (cols[0] && cols[0].includes('/')) {
          const parts = cols[0].trim().split('/');
          if (parts.length === 3 && !isNaN(parts[0])) {
            const month = parts[0].padStart(2, '0');
            const day = parts[1].padStart(2, '0');
            const year = parts[2].length === 2 ? '20' + parts[2] : parts[2];
            currentDate = `${year}-${month}-${day}`;
            // DON'T continue here - check for standings on same line
          }
        }

        // Check for match (only if we have currentDate and it looks like a match row)
        if (currentDate && cols[0] && cols[0].includes(':') && cols[0].includes('-')) {
          const time = cols[0].trim();
          const player1 = cols[1] ? cols[1].trim() : '';
          const player2 = cols[2] ? cols[2].trim() : '';
          const score = cols[3] ? cols[3].trim() : '';

          if (player1 && player2) {
            matches.push({
              date: currentDate,
              time: time,
              player1: normalizePlayerName(player1),
              player2: normalizePlayerName(player2),
              score: score
            });
          }
        }

        // Check for standings (column 4 has position number)
        if (cols[4] && !isNaN(cols[4]) && cols[5]) {
          try {
            const position = parseInt(cols[4]);
            const name = normalizePlayerName(cols[5].trim());
            const matchesPlayed = cols[6] ? parseInt(cols[6]) : 0;
            const points = cols[7] ? parseInt(cols[7]) : 0;

            if (name && name !== 'ΟΝΟΜΑΤΕΠΩΝΥΜΟ') {
              standings.push({
                position: position,
                name: name,
                matches_played: matchesPlayed,
                points: points
              });
            }
          } catch (e) {
            // Skip invalid rows
          }
        }
      }

      // Remove duplicates
      const uniqueStandings = [];
      const seen = new Set();
      for (let s of standings) {
        const key = `${s.position}-${s.name}`;
        if (!seen.has(key)) {
          seen.add(key);
          uniqueStandings.push(s);
        }
      }

      return {
        matches: matches,
        standings: uniqueStandings.sort((a, b) => a.position - b.position)
      };
    }

    function normalizePlayerName(name) {
      if (!name) return '';
      const fixes = {
        'AIBAZOΓΛΟΥ': 'ΑΙΒΑΖΟΓΛΟΥ',
        'MAΓΙΟΠΟΥΛΟΣ': 'ΜΑΓΙΟΠΟΥΛΟΣ'
      };
      return fixes[name] || name;
    }

