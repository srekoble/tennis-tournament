    function formatDate(dateStr) {
      if (!dateStr) return '';
      const [year, month, day] = dateStr.split('-');
      return `${day}/${month}/${year}`;
    }

    function groupMatchesByDate(matches) {
      const grouped = {};
      matches.forEach(match => {
        if (!grouped[match.date]) {
          grouped[match.date] = [];
        }
        grouped[match.date].push(match);
      });
      return grouped;
    }

